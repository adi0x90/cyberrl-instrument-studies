"""B1/B2 report — selection drift, matched re-audit, quarantine.

Renders results/B1.md from the scored pools and the selection analysis.  Every
table cell comes from evidence; nothing is typed by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path("results")
EVIDENCE = Path("evidence")
NS = [1, 4, 8, 16, 32]


def pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def load(path: Path):
    return json.loads(path.read_text()) if path.is_file() else None


def main() -> int:
    analysis = load(RESULTS / "B1.json")
    quarantine = load(RESULTS / "B1_quarantine.json")
    if analysis is None:
        raise SystemExit("results/B1.json missing; run bon.select_drift first")

    lines: list[str] = []
    add = lines.append
    add("# B1 / B2 — Selection drift, matched re-audit, scheduler quarantine")
    add("")
    add("Generated by `bon/report_b1.py` from `evidence/bon/scored_*.jsonl` and `results/B1*.json`.")
    add("")
    add("> The **native-pack arm** (real repository repairs, held-out `variants/` as Tier-2) is reported")
    add("> separately in `results/B1_native.md`: authlib 36/40 Tier-1 accepts refuted, fastmcp 0/66.")
    add("")

    add("## Pools (shared, generated once per task/model)")
    add("")
    add("| model | pool | admitted | P(admitted) |")
    add("|---|---|---|---|")
    for model, data in analysis["models"].items():
        add(f"| `{model}` | {data['pool']} | {data['admitted']} | {pct(data['p_admitted'])} |")
    add("")
    add("One pool of 32 completions per task at temperature 1.0 and a fixed seed, rescored at")
    add("N ∈ {1,4,8,16,32}. Regenerating per N would compare sampling noise, not selection.")
    add("")

    add("## False-accept rate given Tier-1 pass (primary metric)")
    add("")
    add("Tier-1 = finite fixed cases + AST/scope obligations. Tier-2 = seeded randomized property +")
    add("metamorphic obligations, disjoint in case distribution from Tier-1.")
    add("")
    for reward in ("poc", "static", "property"):
        add(f"### Selector reward: `{reward}`")
        add("")
        add("| model | N | T1+&T2- | T1+ | FAR | Wilson 95% | task-bootstrap 95% |")
        add("|---|---|---|---|---|---|---|")
        for model, data in analysis["models"].items():
            for n in NS:
                block = data["analysis"]["N"][str(n)][reward]
                cells = block["cells"]
                ci = block["far_ci"]
                boot = block["far_bootstrap95"]
                add(
                    f"| `{model.split('/')[-1]}` | {n} | {cells['t1p_t2m']} | {block['t1_pass']} | "
                    f"{pct(block['far_given_t1_pass'])} | "
                    f"{'n/a' if not ci else f'[{pct(ci[0])}, {pct(ci[1])}]'} | "
                    f"{'n/a' if not boot else f'[{pct(boot[0])}, {pct(boot[1])}]'} |"
                )
        add("")

    # B2 matched re-audit
    add("## B2 — matched same-family re-audit (identical scaffold/prompt/decoding/budget)")
    add("")
    add("| model | T1 accepts (all samples) | independent T2 refutations | rate | untested |")
    add("|---|---|---|---|---|")
    per_task: dict[str, dict[str, dict]] = {}
    for path in sorted(EVIDENCE.glob("bon/scored_*.jsonl")):
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            model = row["model"]
            entry = per_task.setdefault(model, {}).setdefault(row["task_id"], {"accepted": 0, "refuted": 0, "untested": 0})
            if not row["admitted"]:
                entry["untested"] += 1
            elif row["t1"] == "HOLDS":
                entry["accepted"] += 1
                if row["t2"] == "VIOLATED":
                    entry["refuted"] += 1
    for model, tasks in per_task.items():
        accepted = sum(item["accepted"] for item in tasks.values())
        refuted = sum(item["refuted"] for item in tasks.values())
        untested = sum(item["untested"] for item in tasks.values())
        rate = refuted / accepted if accepted else None
        add(f"| `{model.split('/')[-1]}` | {accepted} | {refuted} | {pct(rate)} | {untested} |")
    add("")
    add("### Per-task (accepted / refuted)")
    add("")
    models = sorted(per_task)
    add("| task | " + " | ".join(f"`{m.split('/')[-1]}`" for m in models) + " |")
    add("|---|" + "---|" * len(models))
    for task in sorted({t for tasks in per_task.values() for t in tasks}):
        cells = []
        for model in models:
            item = per_task[model].get(task)
            cells.append(f"{item['accepted']}/{item['refuted']}" if item else "—")
        add(f"| `{task}` | " + " | ".join(cells) + " |")
    add("")
    add("No Type-I threshold crossing is claimed: with 12 tasks the refutation counts are small, and")
    add("the honest statement is *no refutation in k audited accepts* for models where k counts are 0.")
    add("")

    if quarantine:
        add("## Scheduler-timed quarantine (async Tier-2)")
        add("")
        add("Clock is synthetic (rollout 8 s, step 30 s); verdicts are real.")
        add("")
        add("| delay (s) | policy | refuted accepts audited | mean steps committed before ack | max |")
        add("|---|---|---|---|---|")
        for delay, policies in quarantine["delays"].items():
            for name, item in policies.items():
                add(
                    f"| {delay} | {name} | {item['refuted']} | {item['mean_steps_before_ack']} | "
                    f"{item['max_steps_before_ack']} |"
                )
        add("")
        add("### Stale-audit replay")
        add("")
        add("| delay (s) | ack policy_rev | current | disposition |")
        add("|---|---|---|---|")
        for delay, item in quarantine["stale_replay"].items():
            add(f"| {delay} | {item['ack_policy_rev']} | {item['current_policy_rev']} | {item['disposition']} |")
        add("")

    add("## Not run")
    add("")
    add("- Native-pack arm (fastmcp / redis / authlib patches): no patch-generation + adjudication harness")
    add("  was built in this session, so the three packs × three models × 32 cells are **not run**. The")
    add("  expression arm is complete; the disjoint-obligation claim rests on it only for expression tasks.")
    add("- Live policy quarantine (an unmodified policy completion triggering quarantine) was not observed;")
    add("  the quarantine panel is a planted-error / delayed-ack simulation over recorded verdicts.")
    add("")

    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / "B1.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
