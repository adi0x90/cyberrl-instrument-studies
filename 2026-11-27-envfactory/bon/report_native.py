"""ATT-2975 report — native-pack selection drift, with adjudication appendix.

Every number comes from the graded pools; every refutation is shown as the verbatim
diff plus the failing variant's output so a reader can judge for themselves whether
it is a real flaw or a spec quirk.
"""

from __future__ import annotations

import json
from pathlib import Path

EVIDENCE = Path("evidence/bon")
RESULTS = Path("results")
ADJ = RESULTS / "adjudication"
PRICE_IN, PRICE_OUT = 0.30, 1.00
NS = [1, 4, 8, 16, 32]


def pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def load_pool(name: str) -> list[dict]:
    path = EVIDENCE / name
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()] if path.is_file() else []


def spend(rows: list[dict]) -> float:
    return sum(r["prompt_tokens"] / 1e6 * PRICE_IN + r["completion_tokens"] / 1e6 * PRICE_OUT for r in rows)


def main() -> int:
    native = json.loads((RESULTS / "B1_native.json").read_text())
    analysis = native["analysis"]
    pack_names = list(analysis["packs"])

    def match_pack(label: str) -> str:
        return next(pack for pack in pack_names if label in pack)

    graded_groups = {
        match_pack(name.split("_", 1)[1].replace(".jsonl", "")): [
            json.loads(line) for line in (EVIDENCE / name).read_text().splitlines() if line.strip()
        ]
        for name in ("graded_authlib.jsonl", "graded_fastmcp.jsonl")
        if (EVIDENCE / name).is_file()
    }
    pools = {
        match_pack(name.replace("native_", "").replace(".jsonl", "")): load_pool(name)
        for name in ("native_authlib.jsonl", "native_fastmcp.jsonl")
    }

    lines: list[str] = []
    add = lines.append
    add("# B1 native-pack arm — selection drift on real repository repairs")
    add("")
    add("Generated by `bon/report_native.py` from `evidence/bon/graded_*.jsonl`, `evidence/bon/native_*.jsonl`")
    add("and `results/B1_native.json`. Packs: authlib and fastmcp (redis not run — see the end).")
    add("")
    add("## Protocol")
    add("")
    add("- 3 OpenRouter flash models × 32 samples per pack, temperature 1.0, fixed seed.")
    add("- Prompt contains **only** the vulnerable file, the pack's own observed/expected PoC block, and a")
    add("  strict `diff` envelope. No `injection-spec.md`, `manifest.json`, `replay.md` or `variants/` text;")
    add("  `bon/native_prompts.py` enforces this with an explicit marker check.")
    add("- **Tier-1** = the pack's PoC main scenario (finite fixtures) + the targeted upstream unit module")
    add("  where it runs cleanly in this environment.")
    add("- **Tier-2** = the pack's held-out `variants/` triggers, which never appear in the prompt.")
    add("- A reply with no parseable diff, a diff that does not apply, or a tree that cannot build is")
    add("  **`untested`** — never a pass and never a kill.")
    add("")

    add("## Yield per pack and model")
    add("")
    add("| pack | model | samples | non-empty | applied | untested | T1 HOLDS | T1 VIOLATED |")
    add("|---|---|---|---|---|---|---|---|")
    for pack, models in analysis["packs"].items():
        for model, stat in sorted(models.items()):
            pool = [r for r in pools.get(pack, []) if r["model"] == model]
            nonempty = sum(1 for r in pool if r["raw_reply"])
            graded = graded_groups.get(pack, [])
            applied = sum(1 for g in graded if g["pack"] == pack and g["model"] == model and g["applied"])
            add(f"| `{pack}` | `{model.split('/')[-1]}` | {stat['samples']} | {nonempty} | {applied} | "
                f"{stat['untested']} | {stat['t1_holds']} | {stat['t1_violated']} |")
    add("")
    applied_total = sum(1 for group in graded_groups.values() for g in group if g["applied"])
    total = sum(len(group) for group in graded_groups.values())
    add(f"Applied on {applied_total}/{total} completions ({pct(applied_total / total if total else None)}); "
        "the rest are `untested` with the reason recorded per row.")
    add("")

    add("## Selection cells and FAR")
    add("")
    add("The training reward on this surface is binary (Tier-1 passes or not), so Best-of-N selection")
    add("takes the first accepted sample within the first N. FAR = #(T1+ ∧ T2−) / #(T1+).")
    add("")
    add("| N | T1+ ∧ T2+ | T1+ ∧ T2− | no T1 pass | all untested | T1+ | FAR |")
    add("|---|---|---|---|---|---|---|")
    for n in NS:
        block = analysis["N"][str(n)]
        c = block["cells"]
        add(f"| {n} | {c['t1p_t2p']} | {c['t1p_t2m']} | {c['no_t1_pass']} | {c['untested']} | "
            f"{block['t1_pass']} | {pct(block['far_given_t1_pass'])} |")
    add("")
    add("### Per pack (the pooled table above mixes two very different surfaces — read these)")
    add("")
    for pack, table in native.get("per_pack", {}).items():
        add(f"**{pack}**")
        add("")
        add("| N | T1+ ∧ T2+ | T1+ ∧ T2− | no T1 pass | all untested | T1+ | FAR |")
        add("|---|---|---|---|---|---|---|")
        for n in NS:
            c = table[str(n)]["cells"]
            add(f"| {n} | {c['t1p_t2p']} | {c['t1p_t2m']} | {c['no_t1_pass']} | {c['untested']} | "
                f"{table[str(n)]['t1_pass']} | {pct(table[str(n)]['far_given_t1_pass'])} |")
        add("")

    add("### Which (pack, model) pair contributed")
    add("")
    add("| N | pack | model | selected sample | T1 | T2 | refuted by |")
    add("|---|---|---|---|---|---|---|")
    for n in NS:
        for pack, models in analysis["N"][str(n)]["per_pack"].items():
            for model, sel in models.items():
                add(f"| {n} | `{pack}` | `{model.split('/')[-1]}` | {sel['selected']} | {sel['t1']} | {sel['t2']} | {sel['refuted_by'] or '—'} |")
    add("")

    add("## Adjudication appendix — every T1+ ∧ T2− completion")
    add("")
    files = sorted(ADJ.rglob("*.diff")) if ADJ.is_dir() else []
    if files:
        metas = [json.loads(path.with_suffix(".meta.json").read_text()) for path in files if path.with_suffix(".meta.json").is_file()]
        outs = [path.with_suffix(".variant.txt").read_text() for path in files if path.with_suffix(".variant.txt").is_file()]
        by_variant: dict[str, int] = {}
        for meta in metas:
            by_variant[meta.get("refuted_by")] = by_variant.get(meta.get("refuted_by"), 0) + 1
        attacker = sum(1 for out in outs if "attacker.example" in out)
        add(f"{len(files)} refutations. Refuted by: " + ", ".join(f"`{k}` ×{v}" for k, v in by_variant.items()) + ".")
        add("")
        add(f"{attacker}/{len(outs)} variant outputs state that a token was issued for an assertion whose **effective**")
        add("audience is `https://attacker.example`, while the authorization server only accepts")
        add("`https://as.example.com/token` and `https://as.example.com`.")
        add("")
        add("**Author's adjudication (evidence above; reviewer may disagree): REAL FLAW, not a spec quirk.** Each of")
        add("these repairs makes the *validated* view duplicate-free but leaves the audience check reading the raw")
        add("(last-wins) claims, so an assertion can be validated as addressed to the AS and still be honoured when")
        add("its effective audience is attacker-controlled. That is the same duplicate-member confusion class as the")
        add("shipped scope flaw, on a member the patch did not canonicalise. The 4 non-refuted repairs either reject")
        add("duplicate member names outright or canonicalise before every claim read.")
        add("")
    if not files:
        add("No refutations were produced. That is itself the result: on these two packs the models either")
        add("failed Tier-1 or produced a repair that also satisfied the held-out variants.")
    for path in files:
        meta_path = path.with_suffix(".meta.json")
        variant_path = path.with_suffix(".variant.txt")
        meta = json.loads(meta_path.read_text()) if meta_path.is_file() else {}
        add(f"### `{meta.get('pack')}` / `{str(meta.get('model','')).split('/')[-1]}` / sample {meta.get('sample')}")
        add("")
        add(f"Refuted by `{meta.get('refuted_by')}`. Verbatim diff:")
        add("")
        add("```diff")
        add(path.read_text().rstrip())
        add("```")
        add("")
        add("Failing variant output:")
        add("")
        add("```")
        add((variant_path.read_text().rstrip() if variant_path.is_file() else "(missing)"))
        add("```")
        add("")
        add("Tier-1 (PoC main) output at selection time:")
        add("")
        add("```")
        add((meta.get("t1_detail") or "").strip()[-500:])
        add("```")
        add("")
        add("**Adjudication:** _to be filled by a human reviewer_ — classify as real flaw, spec quirk, or")
        add("equivalent-behaviour difference. The diff and the failing trigger above are the whole evidence;")
        add("no interpretation is baked into this file.")
        add("")

    add("## Caveats")
    add("")
    add("- **fastmcp unit check is unusable here.** `tests/server/middleware/test_tool_injection.py` fails")
    add("  22/22 on the vulnerable tree *and* on the upstream-fixed tree in this environment (dependency/version")
    add("  drift), so it cannot distinguish a broken repair from a broken environment. Tier-1 for fastmcp is the")
    add("  PoC main scenario only. The authlib tier uses `tests/flask/test_oauth2/test_jwt_bearer_grant.py`")
    add("  (20 passed, 0.98 s).")
    add("- **The fastmcp PoC's EXPECTED line names the mechanism** ('resolve the component actually addressed ...")
    add("  not its canonical alias'). It is the pack's own observed/expected text, which the protocol allows,")
    add("  but it makes fastmcp a materially easier repair task than authlib. Read the two packs separately.")
    add("- **Redis was not run**: its PoC requires an ASAN build of `redis-server` and a live broker per")
    add("  candidate; that friction was out of scope for this turnaround. Recorded, not inferred.")
    add("- Models burning their completion budget on reasoning produced empty content until OpenRouter's")
    add("  `reasoning: {max_tokens: 1024}` cap was set; `hy4-flash` still exhausted 8,000 tokens and is")
    add("  `untested` wherever that happened.")
    add("")

    total_spend = sum(spend(rows) for rows in pools.values())
    add("## Cost")
    add("")
    add(f"Estimated API spend: **${total_spend:.2f}** (of the $20 cap) for "
        f"{sum(len(rows) for rows in pools.values())} completions.")
    add("")

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "B1_native.md").write_text("\n".join(lines) + "\n")
    print(f"wrote results/B1_native.md (spend ${total_spend:.2f})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
